package org.firstinspires.ftc.teamcode.Utility;

public class Vector2 {
    public double x, y;



    public Vector2(double x, double y) {
        this.x = x;
        this.y = y;
    }

    public Vector2() {
        this.x = 0;
        this.y = 0;
    }
    public void set(double x, double y) {
        this.x = x;
        this.y = y;
    }

    public void add(Vector2 other) {
        this.x += other.x;
        this.y += other.y;
    }
}


